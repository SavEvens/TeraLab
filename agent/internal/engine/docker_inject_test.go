func callIndex(calls []string, want string) int {
	for index, call := range calls {
		if call == want || strings.HasPrefix(call, want+" ") {
			return index
		}
	}

	return -1
}

func assertCallOrder(t *testing.T, calls []string, first, second string) {
	t.Helper()
	firstIndex := callIndex(calls, first)
	secondIndex := callIndex(calls, second)
	if firstIndex < 0 || secondIndex < 0 {
		t.Fatalf("expected %q before %q in %v", first, second, calls)
	}
	if firstIndex >= secondIndex {
		t.Fatalf("expected %q before %q in %v", first, second, calls)
	}
}

func TestDockerStartInjectsDaemonsAndConfig(t *testing.T) {
	binary, logPath := fakeDocker(t, dockerFreshInjectionBody(0, 0))
	manager := newDockerTestManager(t, binary)
	spec := dockerInjectionSpec(t)
	runDir := t.TempDir()

	info, err := manager.startDocker(spec, runDir)
	if err != nil {
		t.Fatalf("start docker: %v", err)
	}
	if info.State != "running" {
		t.Fatalf("unexpected node info: %+v", info)
	}

	daemonsPath := filepath.Join(runDir, dockerDaemonsRunFile)
	data, err := os.ReadFile(daemonsPath)
	if err != nil {
		t.Fatalf("read injected daemons file: %v", err)
	}
	if string(data) != renderDockerDaemons(spec.Docker.Daemons) {
		t.Fatalf("injected daemons file differs:\n%s", data)
	}
	infoStat, err := os.Stat(daemonsPath)
	if err != nil {
		t.Fatalf("stat injected daemons file: %v", err)
	}
	if mode := infoStat.Mode().Perm(); mode != 0o644 {
		t.Fatalf("daemons file mode = %04o, want 0644", mode)
	}

	configPath := filepath.Join(runDir, dockerConfigRunFile)
	configData, err := os.ReadFile(configPath)
	if err != nil {
		t.Fatalf("read injected config: %v", err)
	}
	if string(configData) != spec.Config {
		t.Fatalf("injected config = %q, want %q", configData, spec.Config)
	}
	configStat, err := os.Stat(configPath)
	if err != nil {
		t.Fatalf("stat injected config: %v", err)
	}
	if mode := configStat.Mode().Perm(); mode != 0o644 {
		t.Fatalf("config file mode = %04o, want 0644", mode)
	}

	calls := dockerCalls(t, logPath)
	for _, expected := range []string{
		fmt.Sprintf("cp %s fakeid:/etc/frr/daemons", daemonsPath),
		fmt.Sprintf("cp %s fakeid:/etc/frr/frr.conf", configPath),
		"start fakeid",
		"exec fakeid chown frr:frr /etc/frr/frr.conf",
	} {
		if !callsContain(calls, expected) {
			t.Fatalf("expected docker call %q in %v", expected, calls)
		}
	}
	assertCallOrder(t, calls, "create -i -t", "cp "+daemonsPath)
	assertCallOrder(t, calls, "cp "+daemonsPath, "start fakeid")
	assertCallOrder(t, calls, "cp "+configPath, "start fakeid")
	manager.Shutdown()
}

func TestDockerStartReusedContainerInjectsFiles(t *testing.T) {
	binary, logPath := fakeDocker(t, dockerReusedInjectionBody(0))
	manager := newDockerTestManager(t, binary)
	spec := dockerInjectionSpec(t)
	runDir := t.TempDir()

	if _, err := manager.startDocker(spec, runDir); err != nil {
		t.Fatalf("start reused docker container: %v", err)
	}
	calls := dockerCalls(t, logPath)
	if callsContain(calls, "create") {
		t.Fatalf("a matching labelled container must be reused: %v", calls)
	}
	for _, expected := range []string{
		fmt.Sprintf("cp %s fakeid:/etc/frr/daemons", filepath.Join(runDir, dockerDaemonsRunFile)),
		fmt.Sprintf("cp %s fakeid:/etc/frr/frr.conf", filepath.Join(runDir, dockerConfigRunFile)),
		"start fakeid",
	} {
		if !callsContain(calls, expected) {
			t.Fatalf("expected docker call %q in %v", expected, calls)
		}
	}
	assertCallOrder(t, calls, fmt.Sprintf("cp %s", filepath.Join(runDir, dockerDaemonsRunFile)), "start fakeid")
	if _, err := os.Stat(filepath.Join(runDir, dockerDaemonsRunFile)); err != nil {
		t.Fatalf("reused start did not write the daemons file: %v", err)
	}
	manager.Shutdown()
}

func TestDockerStartWithoutInjectionOptionsCopiesNothing(t *testing.T) {
	binary, logPath := fakeDocker(t, dockerFreshInjectionBody(0, 0))
	manager := newDockerTestManager(t, binary)
	spec := dockerTestSpec(t)
	spec.Docker.Daemons = nil
	spec.Docker.ConfigPath = ""
	spec.Config = "hostname ignored-without-config-path\n"
	spec.Normalize()
	runDir := t.TempDir()

	if _, err := manager.startDocker(spec, runDir); err != nil {
		t.Fatalf("start docker: %v", err)
	}
	calls := dockerCalls(t, logPath)
	for _, call := range calls {
		if strings.HasPrefix(call, "cp ") {
			t.Fatalf("generic container must not receive docker cp: %v", calls)
		}
	}
	for _, name := range []string{dockerDaemonsRunFile, dockerConfigRunFile} {
		if _, err := os.Stat(filepath.Join(runDir, name)); !os.IsNotExist(err) {
			t.Fatalf("absent options must not write %s: %v", name, err)
		}
	}
	if !callsContain(calls, "start fakeid") {
		t.Fatalf("container was not started: %v", calls)
	}
	manager.Shutdown()
}

func TestDockerStartInjectionFailureRemovesFreshContainer(t *testing.T) {
	binary, logPath := fakeDocker(t, dockerFreshInjectionBody(1, 0))
	manager := newDockerTestManager(t, binary)
	spec := dockerInjectionSpec(t)

	_, err := manager.startDocker(spec, t.TempDir())
	if err == nil {
		t.Fatal("expected the failed docker cp to fail the start")
	}
	for _, expected := range []string{"inject docker node files", "copy /etc/frr/daemons", "fakeid"} {
		if !strings.Contains(err.Error(), expected) {
			t.Fatalf("expected %q in %v", expected, err)
		}
	}
	calls := dockerCalls(t, logPath)
	if !callsContain(calls, "rm -f fakeid") {
		t.Fatalf("a failed fresh start must remove the container: %v", calls)
	}
	if callsContain(calls, "start fakeid") {
		t.Fatalf("the container must not start after a failed injection: %v", calls)
	}
}

