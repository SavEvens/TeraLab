func TestDockerStartChownFailureIsLoggedAndNonFatal(t *testing.T) {
	binary, logPath := fakeDocker(t, dockerFreshInjectionBody(0, 1))
	logs := &lockedLogBuffer{}
	manager := newDockerTestManagerWithLogger(
		t,
		binary,
		slog.New(slog.NewTextHandler(logs, nil)),
	)
	spec := dockerInjectionSpec(t)

	info, err := manager.startDocker(spec, t.TempDir())
	if err != nil {
		t.Fatalf("a chown failure must not fail the node: %v", err)
	}
	if info.State != "running" {
		t.Fatalf("node is not running: %+v", info)
	}
	if !callsContain(dockerCalls(t, logPath), "exec fakeid chown frr:frr /etc/frr/frr.conf") {
		t.Fatal("the post-start chown was not attempted")
	}
	if !strings.Contains(logs.String(), "docker config ownership not applied") {
		t.Fatalf("chown failure was not logged: %s", logs.String())
	}
	manager.Shutdown()
}

func TestDockerDaemonSpecJSONShape(t *testing.T) {
	spec := dockerValidationSpec("quay.io/frrouting/frr:10.7.1")
	spec.Docker = &DockerOptions{
		Daemons:    []string{"zebra", "ospfd", "bgpd"},
		ConfigPath: "/etc/frr/frr.conf",
	}
	payload, err := json.Marshal(spec)
	if err != nil {
		t.Fatalf("marshal spec: %v", err)
	}
	var decoded struct {
		Docker map[string]any `json:"docker"`
	}
	if err := json.Unmarshal(payload, &decoded); err != nil {
		t.Fatalf("decode spec: %v", err)
	}
	daemons, ok := decoded.Docker["daemons"].([]any)
	if !ok || len(daemons) != 3 || daemons[0] != "zebra" {
		t.Fatalf("unexpected daemons JSON: %v", decoded.Docker["daemons"])
	}
	if decoded.Docker["config_path"] != "/etc/frr/frr.conf" {
		t.Fatalf("unexpected config_path JSON: %v", decoded.Docker["config_path"])
	}

	spec.Docker = &DockerOptions{}
	payload, err = json.Marshal(spec)
	if err != nil {
		t.Fatalf("marshal spec without injection: %v", err)
	}
	if strings.Contains(string(payload), `"daemons"`) || strings.Contains(string(payload), `"config_path"`) {
		t.Fatalf("absent injection options must be omitted: %s", payload)
	}
}

// TestDockerIntegrationInjectsDaemonsAndConfig runs against a real FRR image
// and is skipped unless TERALAB_DOCKER_INTEGRATION=1. The image must be
// present locally (no pull): set TERALAB_DOCKER_FRR_TEST_IMAGE to override
// the pinned default.
func TestDockerIntegrationInjectsDaemonsAndConfig(t *testing.T) {
	if os.Getenv("TERALAB_DOCKER_INTEGRATION") != "1" {
		t.Skip("set TERALAB_DOCKER_INTEGRATION=1 to run docker integration tests")
	}
	binary := os.Getenv("TERALAB_DOCKER")
	if binary == "" {
		binary = "/usr/bin/docker"
	}
	if _, err := os.Stat(binary); err != nil {
		t.Skipf("docker binary not found at %s", binary)
	}
	if err := exec.Command(binary, "info").Run(); err != nil {
		t.Skipf("docker daemon is not reachable: %v", err)
	}
	image := os.Getenv("TERALAB_DOCKER_FRR_TEST_IMAGE")
	if image == "" {
		image = "quay.io/frrouting/frr:10.7.1"
	}
	if err := exec.Command(binary, "image", "inspect", image).Run(); err != nil {
		t.Skipf("local FRR image %s is not present; pull it first", image)
	}

	cfg := config.Config{
		RunDir:         t.TempDir(),
		ImagesDir:      t.TempDir(),
		CgroupRoot:     t.TempDir(),
		DisableCgroups: true,
		NetworkBackend: network.BackendLinux,
		VMUser:         "teralab-vm",
		DockerBinary:   binary,
		AllowRootVM:    true,
	}
	manager := NewManager(cfg, slog.New(slog.NewTextHandler(os.Stderr, nil)))
	spec := Spec{
		ID:       "dockerfrr" + strconv.FormatInt(time.Now().UnixNano(), 10),
		Name:     "FRR integration",
		Engine:   "docker",
		Image:    image,
		Ethernet: 0,
		Config:   "frr version 10.7.1\nhostname teralab-int\n!\n",
		Docker: &DockerOptions{
			ConsoleCommand: "/usr/bin/vtysh",
			CapAdd:         []string{"NET_ADMIN", "SYS_ADMIN"},
			Daemons:        []string{"zebra", "ospfd", "bgpd"},
			ConfigPath:     "/etc/frr/frr.conf",
			Pull:           boolPointer(false),
		},
	}
	spec.Normalize()
	if err := spec.Validate(nil); err != nil {
		t.Fatalf("integration spec does not validate: %v", err)
	}
	t.Cleanup(func() { _ = manager.Wipe(spec.ID) })

	info, err := manager.Start(spec)
	if err != nil {
		t.Fatalf("start FRR integration node: %v", err)
	}
	if info.State != "running" {
		t.Fatalf("unexpected node info: %+v", info)
	}
	containerID := manager.nodes[spec.ID].ContainerID
	if containerID == "" {
		t.Fatal("started container has no id")
	}

	daemons, err := exec.Command(binary, "exec", containerID, "cat", dockerDaemonsPath).Output()
	if err != nil {
		t.Fatalf("read injected daemons file from the container: %v", err)
	}
	if string(daemons) != renderDockerDaemons(spec.Docker.Daemons) {
		t.Fatalf("container daemons file differs:\n%s", daemons)
	}
	configData, err := exec.Command(binary, "exec", containerID, "cat", spec.Docker.ConfigPath).Output()
	if err != nil {
		t.Fatalf("read injected config from the container: %v", err)
	}
	if string(configData) != spec.Config {
		t.Fatalf("container config = %q, want %q", configData, spec.Config)
	}
	if err := manager.Wipe(spec.ID); err != nil {
		t.Fatalf("wipe: %v", err)
	}
}
