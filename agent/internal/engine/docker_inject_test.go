func TestRenderDockerDaemonsSelectionAndOrder(t *testing.T) {
	cases := []struct {
		name    string
		daemons []string
		yes     []string
	}{
		{
			name:    "order does not matter",
			daemons: []string{"pathd", "bgpd", "zebra"},
			yes:     []string{"zebra", "bgpd", "pathd"},
		},
		{
			name:    "ipv6 daemons keep their options",
			daemons: []string{"ospf6d", "ripngd", "pim6d", "bfdd"},
			yes:     []string{"ospf6d", "ripngd", "pim6d", "bfdd"},
		},
		{
			name:    "empty selection disables everything",
			daemons: nil,
			yes:     nil,
		},
	}
	for _, testCase := range cases {
		t.Run(testCase.name, func(t *testing.T) {
			rendered := renderDockerDaemons(testCase.daemons)
			selected := map[string]bool{}
			for _, daemon := range testCase.yes {
				selected[daemon] = true
			}

			lines := strings.Split(strings.TrimSuffix(rendered, "\n"), "\n")
			seenDaemons := map[string]int{}
			seenOptions := map[string]int{}
			var daemonOrder []string
			for _, line := range lines {
				for _, daemon := range dockerDaemonAllowlist {
					if line == daemon+"=yes" || line == daemon+"=no" {
						seenDaemons[daemon]++
						daemonOrder = append(daemonOrder, daemon)
					}
					if strings.HasPrefix(line, daemon+"_options=") {
						seenOptions[daemon]++
					}
				}
			}
			if len(daemonOrder) != len(dockerDaemonAllowlist) {
				t.Fatalf("expected one yes/no line per allowlisted daemon, got %v", daemonOrder)
			}
			for index, daemon := range dockerDaemonAllowlist {
				if daemonOrder[index] != daemon {
					t.Fatalf("daemon order changed at %d: got %q, want %q", index, daemonOrder[index], daemon)
				}
				if seenDaemons[daemon] != 1 || seenOptions[daemon] != 1 {
					t.Fatalf(
						"daemon %s rendered %d status lines and %d options lines",
						daemon,
						seenDaemons[daemon],
						seenOptions[daemon],
					)
				}
				want := "=no"
				if selected[daemon] {
					want = "=yes"
				}
				if !strings.Contains(rendered, "\n"+daemon+want+"\n") {
					t.Fatalf("expected %s%s in\n%s", daemon, want, rendered)
				}
			}
			if !strings.Contains(rendered, "vtysh_enable=yes\n") {
				t.Fatalf("vtysh_enable is missing:\n%s", rendered)
			}
			for _, daemon := range dockerDaemonAllowlist {
				want := daemon + `_options="` + dockerDaemonOptions[daemon] + `"`
				if !strings.Contains(rendered, want) {
					t.Fatalf("expected %q in\n%s", want, rendered)
				}
			}
			for _, daemon := range dockerFixedDaemonOptions {
				want := daemon.name + `_options="` + daemon.options + `"`
				if strings.Count(rendered, want) != 1 {
					t.Fatalf("expected exactly one %q in\n%s", want, rendered)
				}
			}
			pathdOptions := `pathd_options="  -A 127.0.0.1"`
			mgmtdOptions := `mgmtd_options="  -A 127.0.0.1"`
			staticdOptions := `staticd_options="-A 127.0.0.1"`
			if !(strings.Index(rendered, pathdOptions) < strings.Index(rendered, mgmtdOptions) &&
				strings.Index(rendered, mgmtdOptions) < strings.Index(rendered, staticdOptions)) {
				t.Fatalf("fixed daemon options must follow the allowlisted options:\n%s", rendered)
			}
		})
	}
}

func dockerInjectionSpec(t *testing.T) Spec {
	t.Helper()
	spec := dockerTestSpec(t)
	// Keep the fixture image aligned with the fake docker inspect payloads.
	spec.Image = "quay.io/frrouting/frr:10.7.1"
	spec.Docker.Daemons = []string{"zebra", "ospfd", "bgpd"}
	spec.Docker.ConfigPath = "/etc/frr/frr.conf"
	spec.Config = "frr version 10.7.1\nhostname teralab\n!\n"
	spec.Normalize()
	if err := spec.Validate(nil); err != nil {
		t.Fatalf("injection spec does not validate: %v", err)
	}

	return spec
}

func dockerFreshInjectionBody(cpExit, chownExit int) string {
	return fmt.Sprintf(`case "$1" in
image) exit 0 ;;
inspect)
  if [ "$2" = "teralab-node-1" ]; then
    echo "Error: No such object: $2" >&2
    exit 1
  fi
  echo '[{"Id":"fakeid","Config":{"Image":"quay.io/frrouting/frr:10.7.1","Labels":{"teralab.node":"node-1","teralab.lab":"lab-1"}},"State":{"Status":"running","Running":true,"Pid":4242},"NetworkSettings":{}}]'
  ;;
create) echo fakeid ;;
cp) exit %d ;;
exec)
  if [ "$2" = "fakeid" ] && [ "$3" = "chown" ]; then
    echo "chown: invalid user: frr" >&2
    exit %d
  fi
  exit 0 ;;
start) exit 0 ;;
*) exit 0 ;;
esac`, cpExit, chownExit)
}

