# Debian postrm for TeraLab. Purge removes only the runtime directory; labs,
# images, the database, configuration, the agent secret and the setup token are
# operator data and are kept.
set -e

case "$1" in
purge)
	# prerm already disabled the Apache configuration on remove; dpkg has
	# removed the conffile by now, so there is nothing left to disable here.
	# The opt-in KSM unit and drop-ins and the generated identity drop-in are
	# written by apply-state.sh, not shipped as package files, so purge removes
	# them explicitly. Operator drop-ins with other names are left alone.
	if command -v systemctl >/dev/null 2>&1; then
		systemctl disable teralab-ksm.service >/dev/null 2>&1 || true
	fi
	rm -f /etc/systemd/system/teralab-ksm.service \
		/etc/systemd/system/docker.service.d/ksm.conf \
		/etc/systemd/system/teralab-agent.service.d/ksm.conf \
		/etc/systemd/system/teralab-agent.service.d/10-teralab-identity.conf \
		/etc/systemd/system/php8.4-fpm.service.d/10-teralab-socket-acl.conf \
		2>/dev/null || true
	rmdir /etc/systemd/system/teralab-agent.service.d \
		/etc/systemd/system/php8.4-fpm.service.d >/dev/null 2>&1 || true
	if command -v systemctl >/dev/null 2>&1; then
		systemctl daemon-reload >/dev/null 2>&1 || true
	fi
	if rm -rf /run/teralab 2>/dev/null; then
		printf 'teralab: removed /run/teralab.\n'
	else
		printf 'teralab: warning: could not remove /run/teralab\n' >&2
	fi
	# The legacy compatibility link is generated by apply-state.sh; remove it
	# only when it still points at the install root we just deleted.
	if [ -L /opt/unetlab ] && [ "$(readlink /opt/unetlab)" = "/opt/teralab" ]; then
		rm -f /opt/unetlab
		printf 'teralab: removed /opt/unetlab compatibility link.\n'
	fi
	printf 'teralab: /var/lib/teralab (labs, images and the database) was not deleted; purge never removes operator data.\n'
	printf 'teralab: /etc/teralab (config.php, if any, the agent secret and the setup token) was kept for a future reinstall.\n'
	;;
esac

exit 0
