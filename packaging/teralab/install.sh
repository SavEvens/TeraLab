# Install TeraLab v1.6-dev on a Debian 13 host.
#
# The installer never overwrites configuration, the database, labs, or images.
# It is safe to re-run and is the supported upgrade path from v1.1.
#
# This script owns the source copy and the build steps only. Every host state
# mutation lives in apply-state.sh, which the Debian package's postinst calls
# as well, so source installs and the package cannot drift apart.
set -Eeuo pipefail

ROOT="/opt/teralab"
DATA="/var/lib/teralab"
SOURCE="$(cd "$(dirname "$0")/../.." && pwd)"
AGENT_BINARY=""
INSTALL_SYSTEMD=1
INSTALL_KSM=0

usage() {
	cat <<EOF
Usage: packaging/teralab/install.sh [options]

Options:
  --root PATH            Install root (default: $ROOT)
  --data PATH            Runtime state (default: $DATA)
  --source PATH          Source tree (default: $SOURCE)
  --agent-binary PATH    Prebuilt teralab-agent (default: build with go)
  --no-systemd           Do not install or reload the systemd unit
  --ksm                  Enable Kernel Samepage Merging for labs and containers
  -h, --help             Show this help

Dependencies: rsync, composer (when api/vendor is absent), Go (when no agent
binary is supplied), Node/npm (to build the Vue UI when ui/dist is absent).
apply-state.sh checks php >= 8.4 with sqlite3, php8.4-fpm with setfacl (the acl
package), qemu-system-x86_64 and qemu-img.
EOF
}

while [ "$#" -gt 0 ]; do
	case "$1" in
		--root) ROOT="$2"; shift 2 ;;
		--data) DATA="$2"; shift 2 ;;
		--source) SOURCE="$2"; shift 2 ;;
		--agent-binary) AGENT_BINARY="$2"; shift 2 ;;
		--no-systemd) INSTALL_SYSTEMD=0; shift ;;
		--ksm) INSTALL_KSM=1; shift ;;
		-h|--help) usage; exit 0 ;;
		*) usage >&2; exit 2 ;;
	esac
done

if [ "$(id -u)" -ne 0 ]; then
	printf 'run as root\n' >&2
	exit 1
fi

command -v rsync >/dev/null || { echo "rsync is required" >&2; exit 1; }
command -v setfacl >/dev/null || { echo "setfacl is required (install the acl package)" >&2; exit 1; }

if [ ! -d "$SOURCE/api" ]; then
	printf 'source tree not found: %s\n' "$SOURCE" >&2
	exit 1
fi
if [ ! -f "$SOURCE/api/vendor/autoload.php" ]; then
	command -v composer >/dev/null || { echo "composer is required to install API dependencies" >&2; exit 1; }
	( cd "$SOURCE/api" && composer install --no-dev --no-interaction --prefer-dist )
fi

install -d -m 0755 "$ROOT"
rsync -a --delete \
	--exclude '.git' \
	--exclude 'AGENTS.md' \
	--exclude 'agent/teralab-agent' \
	--exclude 'agent/bin' \
	--exclude 'dist' \
	--exclude 'node_modules' \
	--exclude 'ui/node_modules' \
	--exclude 'ui/dist' \
	"$SOURCE/" "$ROOT/"

install -d -m 0755 "$ROOT/bin"
if [ -f "$ROOT/ui/package.json" ]; then
	if [ ! -d "$ROOT/ui/dist" ]; then
		if command -v npm >/dev/null 2>&1; then
			( cd "$ROOT/ui" && npm ci --no-audit --no-fund && npm run build )
		else
			printf 'warning: npm not found; the Vue UI will not be built\n' >&2
		fi
	fi
	if [ -d "$ROOT/ui/dist" ]; then
		install -d -m 0755 "$ROOT/html/ui"
		cp -a "$ROOT/ui/dist/." "$ROOT/html/ui/"
	fi
fi
if [ -n "$AGENT_BINARY" ]; then
	install -m 0755 "$AGENT_BINARY" "$ROOT/bin/teralab-agent"
else
	command -v go >/dev/null || { echo "go is required to build teralab-agent (or use --agent-binary)" >&2; exit 1; }
	( cd "$ROOT/agent" && go build -o "$ROOT/bin/teralab-agent" ./cmd/teralab-agent )
fi

# The installed tree is product code, never build-user state. It must not be
# writable by the API identity, the engine identities or www-data: a
# privileged process (the agent) executes and loads files from here.
chown -R root:root "$ROOT"
chmod -R go-w "$ROOT"
chmod 0755 "$ROOT/bin/teralab-agent"

apply_args=(--root "$ROOT" --data "$DATA")
if [ "$INSTALL_SYSTEMD" -eq 0 ]; then
	apply_args+=(--no-systemd)
fi
if [ "$INSTALL_KSM" -eq 1 ]; then
	apply_args+=(--ksm)
fi

# The setup token is generated by apply-state.sh. Remember whether it already
# existed so the secret value is printed only on the run that creates it; a
# re-run or an upgrade points the operator at the root-owned token file instead.
SETUP_TOKEN_FILE="/etc/teralab/setup.token"
setup_token_existed=0
if [ -f "$SETUP_TOKEN_FILE" ]; then
	setup_token_existed=1
fi

"$ROOT/packaging/teralab/apply-state.sh" "${apply_args[@]}"

printf 'TeraLab installed at %s\n' "$ROOT"
printf 'Runtime data: %s\n' "$DATA"
printf 'Lab bridge firewall rule: %s\n' "$(systemctl is-active teralab-firewall.service 2>/dev/null || echo manual)"
if [ "$setup_token_existed" -eq 0 ] && [ -f "$SETUP_TOKEN_FILE" ]; then
	printf '\nTeraLab first-run setup token (shown once): %s\n' "$(cat -- "$SETUP_TOKEN_FILE")"
	printf 'The token is also stored at %s (0640 root:teralab); it is not printed again.\n' "$SETUP_TOKEN_FILE"
else
	printf 'TeraLab setup token: %s (already present; not printed again)\n' "$SETUP_TOKEN_FILE"
fi
printf 'First-run setup: open /ui/ or POST /api/v2/setup (only while no administrator exists).\n'
printf 'Send the token in the request header: X-TeraLab-Setup-Token: <token>\n'
printf 'Next: complete first-run setup (one time), then log in.\n'
